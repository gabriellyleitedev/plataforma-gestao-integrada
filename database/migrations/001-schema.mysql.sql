CREATE TABLE IF NOT EXISTS users (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL, active INT NOT NULL DEFAULT 1, created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash VARCHAR(64) PRIMARY KEY, user_id INT NOT NULL, expires_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS clients (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL DEFAULT '',
 phone VARCHAR(40) NOT NULL DEFAULT '', document VARCHAR(40) NOT NULL DEFAULT '', notes TEXT NOT NULL,
 archived INT NOT NULL DEFAULT 0, created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, description TEXT NOT NULL,
 archived INT NOT NULL DEFAULT 0, created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS suppliers (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL DEFAULT '',
 phone VARCHAR(40) NOT NULL DEFAULT '', document VARCHAR(40) NOT NULL DEFAULT '', notes TEXT NOT NULL,
 archived INT NOT NULL DEFAULT 0, created_at VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS items (
 id INT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(160) NOT NULL, type VARCHAR(20) NOT NULL,
 sku VARCHAR(80) NOT NULL DEFAULT '', description TEXT NOT NULL, price_cents INT NOT NULL, cost_cents INT NOT NULL DEFAULT 0,
 category_id INT NULL, supplier_id INT NULL, stock_minimum INT NOT NULL DEFAULT 0, stock INT NOT NULL DEFAULT 0,
 archived INT NOT NULL DEFAULT 0, created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (category_id) REFERENCES categories(id), FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
);
CREATE TABLE IF NOT EXISTS sales (
 id INT PRIMARY KEY AUTO_INCREMENT, client_id INT NULL, user_id INT NOT NULL,
 total_cents INT NOT NULL, payment_method VARCHAR(30) NOT NULL, status VARCHAR(20) NOT NULL,
 notes TEXT NOT NULL, created_at VARCHAR(30) NOT NULL, cancelled_at VARCHAR(30) NULL,
 FOREIGN KEY (client_id) REFERENCES clients(id), FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS sale_items (
 id INT PRIMARY KEY AUTO_INCREMENT, sale_id INT NOT NULL, item_id INT NOT NULL,
 name VARCHAR(160) NOT NULL, type VARCHAR(20) NOT NULL, quantity INT NOT NULL,
 price_cents INT NOT NULL, cost_cents INT NOT NULL,
 FOREIGN KEY (sale_id) REFERENCES sales(id), FOREIGN KEY (item_id) REFERENCES items(id)
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id INT PRIMARY KEY AUTO_INCREMENT, item_id INT NOT NULL, user_id INT NOT NULL, sale_id INT NULL,
 type VARCHAR(20) NOT NULL, quantity INT NOT NULL, balance_after INT NOT NULL, reason VARCHAR(500) NOT NULL, created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (item_id) REFERENCES items(id), FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (sale_id) REFERENCES sales(id)
);
CREATE TABLE IF NOT EXISTS appointments (
 id INT PRIMARY KEY AUTO_INCREMENT, client_id INT NOT NULL, user_id INT NOT NULL,
 subject VARCHAR(160) NOT NULL, notes TEXT NOT NULL, scheduled_at VARCHAR(30) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'open', archived INT NOT NULL DEFAULT 0, created_at VARCHAR(30) NOT NULL,
 FOREIGN KEY (client_id) REFERENCES clients(id), FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS setup_lock (id INT PRIMARY KEY);
